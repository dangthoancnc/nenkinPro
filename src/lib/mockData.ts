// Helper to generate full-character split tags (no empty slot in mock preview)
const generateSplitValues = (prefix: string, value: string, count: number, fillChar = '') => {
  for (let i = 0; i < count; i++) {
    if (i < value.length) {
      MOCK_DATA[`${prefix}_${i + 1}`] = value[i];
    } else {
      MOCK_DATA[`${prefix}_${i + 1}`] = fillChar || (i < 9 ? String(i + 1) : 'X');
    }
  }
};

// Helper for right-aligned numeric digit boxes (e.g. 7-box monetary grids)
function generateSplitDigitsRight(prefix: string, valueStr: string, count = 7) {
  const digits = valueStr.replace(/\D/g, '');
  for (let i = 1; i <= count; i++) {
    const offsetFromRight = count - i;
    if (offsetFromRight < digits.length) {
      MOCK_DATA[`${prefix}_${i}`] = digits[digits.length - 1 - offsetFromRight];
    } else {
      MOCK_DATA[`${prefix}_${i}`] = '0';
    }
  }
}

